// @ts-check
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const parser = await readFile(path.join(root, 'src/parser.c'), 'utf8');
const grammar = JSON.parse(await readFile(path.join(root, 'src/grammar.json'), 'utf8'));
/** @type {Set<string>} */
const keywords = new Set();
collectKeywords(grammar, keywords);
/** @type {Set<string>} */
const groupModifiers = new Set();
for (const rule of [
  'attribute_specifier',
  'ms_declspec_modifier',
  'gnu_asm_expression',
  'alignas_qualifier',
  'typeof_specifier',
  'atomic_type_specifier',
  'bit_int_specifier',
])
  collectKeywords(grammar.rules[rule], groupModifiers);
/** @type {Set<string>} */
const declarationModifiers = new Set();
for (const rule of [
  'type_qualifier',
  'alignas_qualifier',
  'ms_call_modifier',
  'ms_declspec_modifier',
  'attribute_specifier',
  'gnu_asm_expression',
])
  collectKeywords(grammar.rules[rule], declarationModifiers);
/** @type {Set<string>} */
const typeKeywords = new Set();
/** @type {Set<string>} */
const scalarTypeKeywords = new Set();
for (const rule of ['primitive_type', 'sized_type_specifier']) collectKeywords(grammar.rules[rule], scalarTypeKeywords);
collectTypeKeywords(grammar.rules._non_identifier_type_specifier, typeKeywords);
const sortedKeywords = [...keywords].toSorted();
const keywordTable = `#define FUNCTION_MACRO_KEYWORD_MAX_LENGTH ${Math.max(...sortedKeywords.map((word) => word.length))}
static const char *const function_macro_keywords[] = {
${sortedKeywords.map((word) => `  ${JSON.stringify(word)},`).join('\n')}
};
static const char *const function_macro_group_modifiers[] = {
${[...groupModifiers]
  .toSorted()
  .map((word) => `  ${JSON.stringify(word)},`)
  .join('\n')}
};
static const char *const function_macro_type_keywords[] = {
${[...typeKeywords]
  .toSorted()
  .map((word) => `  ${JSON.stringify(word)},`)
  .join('\n')}
};
static const char *const function_macro_scalar_type_keywords[] = {
${[...scalarTypeKeywords]
  .toSorted()
  .map((word) => `  ${JSON.stringify(word)},`)
  .join('\n')}
};
static const char *const function_macro_declaration_modifiers[] = {
${[...declarationModifiers]
  .toSorted()
  .map((word) => `  ${JSON.stringify(word)},`)
  .join('\n')}
};

`;
const predicates = [1, 2].map((index) => {
  const match = parser.match(
    new RegExp(`\\b(ts_lex_\\w+\\(ts_lex_sym_identifier_character_set_${index}_ascii,[^\\n;]*?lookahead\\))`)
  );
  assert.ok(match?.[1], `Missing generated identifier predicate ${index}`);
  return match[1];
});
await mkdir(path.join(root, '.tmp'), { recursive: true });
const temporary = await mkdtemp(path.join(root, '.tmp/identifier-ranges-'));
try {
  const source = path.join(temporary, 'ranges.c');
  const executable = path.join(temporary, 'ranges');
  await writeFile(
    source,
    `
#include <stdio.h>
#include <stdlib.h>
#include ${JSON.stringify(path.join(root, 'src/parser.c'))}

// Only character predicates are evaluated; a scanner call is a generator bug.
void *tree_sitter_c_external_scanner_create(void) { abort(); }
void tree_sitter_c_external_scanner_destroy(void *payload) { abort(); }
bool tree_sitter_c_external_scanner_scan(void *payload, TSLexer *lexer, const bool *valid) { abort(); }
unsigned tree_sitter_c_external_scanner_serialize(void *payload, char *buffer) { abort(); }
void tree_sitter_c_external_scanner_deserialize(void *payload, const char *buffer, unsigned length) { abort(); }

int main(void) {
  for (int table = 0; table < 2; table++) {
    printf("static const TSCharacterRange preproc_identifier_%s[] = {\\n", table ? "continue" : "start");
    int32_t start = -1;
    unsigned column = 0;
    for (int32_t lookahead = 0; lookahead <= 0x110000; lookahead++) {
      bool member = lookahead < 0x110000 && (table ? ${predicates[1]} : ${predicates[0]});
      if (member && start < 0) start = lookahead;
      if (!member && start >= 0) {
        printf("%s{0x%x, 0x%x},%s", column ? " " : "  ", (unsigned)start, (unsigned)(lookahead - 1), column == 7 ? "\\n" : "");
        column = (column + 1) % 8;
        start = -1;
      }
    }
    printf("%s};\\n\\n", column ? "\\n" : "");
  }
}
`
  );
  execFileSync('cc', ['-std=c11', '-I', path.join(root, 'src'), source, '-o', executable]);
  const tables = execFileSync(executable, { encoding: 'utf8' });
  await writeFile(
    path.join(root, 'src/identifier.h'),
    `// Generated by script/generateIdentifierRanges.js from parser identifier predicates.
#ifndef TREE_SITTER_C_IDENTIFIER_H_
#define TREE_SITTER_C_IDENTIFIER_H_

#include "tree_sitter/parser.h"

${tables}#endif
`
  );
  await writeFile(
    path.join(root, 'src/keywords.h'),
    `// Generated by script/generateIdentifierRanges.js from standalone grammar token words.
#ifndef TREE_SITTER_C_KEYWORDS_H_
#define TREE_SITTER_C_KEYWORDS_H_

${keywordTable}#endif
`
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}

/**
 * @param {unknown} value
 * @param {Set<string>} output
 */
function collectTypeKeywords(value, output) {
  if (!value || typeof value !== 'object') return;
  if ('type' in value && value.type === 'SYMBOL' && 'name' in value && typeof value.name === 'string') {
    collectKeywords(grammar.rules[value.name], output);
    return;
  }
  for (const child of Object.values(value)) collectTypeKeywords(child, output);
}

/**
 * @param {unknown} value
 * @param {Set<string>} output
 * @param {boolean} lexical
 */
function collectKeywords(value, output, lexical = false) {
  if (!value || typeof value !== 'object') return;
  if (lexical && 'type' in value && value.type === 'SEQ') return;
  const token = lexical || ('type' in value && (value.type === 'TOKEN' || value.type === 'IMMEDIATE_TOKEN'));
  if (
    'type' in value &&
    value.type === 'STRING' &&
    'value' in value &&
    typeof value.value === 'string' &&
    /^[A-Za-z_][A-Za-z_0-9]*$/.test(value.value)
  ) {
    output.add(value.value);
  }
  for (const child of Object.values(value)) collectKeywords(child, output, token);
}
