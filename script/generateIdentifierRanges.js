/**
 * @param {string} parserSource
 */
function buildIdentifierTables(parserSource) {
  const symbolMatch = parserSource.match(/^\s*sym_identifier\s*=\s*(\d+),/m);
  const tableMatch = parserSource.match(/static const uint16_t ts_lex_table\[\]\s*=\s*\{([\s\S]*?)\};/);
  assert.ok(symbolMatch?.[1] && tableMatch?.[1], 'Missing sym_identifier or ts_lex_table in src/parser.c');
  const identifierSymbol = Number(symbolMatch[1]);
  const words = Uint16Array.from(tableMatch[1].match(/\d+/g) ?? [], Number);
  const lex = createLexTableReader(words);
  const continuationState = lex.nextState(0, lex.asciiClass(0x71));
  assert.ok(continuationState >= 0 && lex.accepts(continuationState, identifierSymbol), 'Missing identifier state');

  const startClasses = classifyIdentifierClasses(lex, 0, identifierSymbol);
  const continueClasses = classifyIdentifierClasses(lex, continuationState, identifierSymbol);
  return `${formatCharacterRanges('start', lex, startClasses)}${formatCharacterRanges('continue', lex, continueClasses)}${formatAsciiMask('start', lex, startClasses)}${formatAsciiMask('continue', lex, continueClasses)}\n`;
}

/**
 * @param {ReturnType<typeof createLexTableReader>} lex
 * @param {number} fromState
 * @param {number} symbol
 */
function classifyIdentifierClasses(lex, fromState, symbol) {
  const matched = new Uint8Array(lex.classCount);
  for (let cls = 0; cls < lex.classCount; cls++) {
    const next = lex.nextState(fromState, cls);
    if (next < 0) continue;
    const escaped = lex.stepAscii(next, 'u0041');
    if (lex.accepts(next, symbol) || (escaped >= 0 && lex.accepts(escaped, symbol))) matched[cls] = 1;
  }
  return matched;
}

/**
 * @param {string} suffix
 * @param {ReturnType<typeof createLexTableReader>} lex
 * @param {Uint8Array} matchedClasses
 */
function formatCharacterRanges(suffix, lex, matchedClasses) {
  const entries = collectCharacterRanges(lex, matchedClasses);
  let lines = `static const TSCharacterRange preproc_identifier_${suffix}[] = {\n`;
  for (let i = 0; i < entries.length; i++) {
    const column = i % 8;
    lines += `${column ? ' ' : '  '}${entries[i]}${column === 7 || i === entries.length - 1 ? '\n' : ''}`;
  }
  return `${lines}};\n\n`;
}

/**
 * @param {ReturnType<typeof createLexTableReader>} lex
 * @param {Uint8Array} matchedClasses
 */
function collectCharacterRanges(lex, matchedClasses) {
  /** @type {string[]} */
  const entries = [];
  let rangeStart = -1;
  const visit = (/** @type {number} */ start, /** @type {number} */ endExclusive, /** @type {number} */ cls) => {
    if (matchedClasses[cls]) rangeStart = rangeStart < 0 ? start : rangeStart;
    else if (rangeStart >= 0) {
      entries.push(`{0x${rangeStart.toString(16)}, 0x${(start - 1).toString(16)}},`);
      rangeStart = -1;
    }
    return endExclusive;
  };
  let cursor = 0;
  for (let cp = 0; cp < 128; cp++) cursor = visit(cp, cp + 1, lex.asciiClass(cp));
  for (let i = 0; i < lex.unicodeRanges; i++) cursor = visit(cursor, lex.unicodeEnd(i) + 1, lex.unicodeClass(i));
  if (rangeStart >= 0) entries.push(`{0x${rangeStart.toString(16)}, 0x${(cursor - 1).toString(16)}},`);
  return entries;
}

/**
 * @param {string} suffix
 * @param {ReturnType<typeof createLexTableReader>} lex
 * @param {Uint8Array} matchedClasses
 */
function formatAsciiMask(suffix, lex, matchedClasses) {
  let low = 0n;
  let high = 0n;
  for (let cp = 0; cp < 64; cp++) {
    if (matchedClasses[lex.asciiClass(cp)]) low |= 1n << BigInt(cp);
    if (matchedClasses[lex.asciiClass(cp + 64)]) high |= 1n << BigInt(cp);
  }
  const lowHex = low.toString(16).padStart(16, '0');
  const highHex = high.toString(16).padStart(16, '0');
  return `static const uint64_t preproc_identifier_${suffix}_ascii[] = {0x${lowHex}ull, 0x${highHex}ull};\n`;
}

/**
 * @param {Uint16Array} t
 */
function createLexTableReader(t) {
  const word = (/** @type {number} */ i) => t[i] ?? 0;
  const readU32 = (/** @type {number} */ i) => (word(i) | (word(i + 1) << 16)) >>> 0;
  const stateCount = word(2);
  const classCount = word(4);
  const unicodeRanges = word(5);
  const wideBase = (word(6) & 0x40_00) !== 0;
  const combLen = readU32(7);
  const extTransLen = readU32(9);
  const unicodeEndsOff = 141;
  const unicodeClassesOff = unicodeEndsOff + unicodeRanges * 2;
  const stateMetaOff = unicodeClassesOff + unicodeRanges;
  const combOff = stateMetaOff + stateCount * (wideBase ? 5 : 4);
  const extTransOff = combOff + combLen * 2;
  const extAcceptsOff = extTransOff + extTransLen;
  const layout = { word, readU32, wideBase, combLen, stateMetaOff, combOff, extTransOff, extAcceptsOff };
  const asciiClass = (/** @type {number} */ cp) => word(13 + cp);
  const nextState = (/** @type {number} */ state, /** @type {number} */ cls) => readNextState(layout, state, cls);
  return {
    classCount,
    unicodeRanges,
    asciiClass,
    unicodeEnd: (/** @type {number} */ i) => readU32(unicodeEndsOff + i * 2),
    unicodeClass: (/** @type {number} */ i) => word(unicodeClassesOff + i),
    nextState,
    accepts: (/** @type {number} */ state, /** @type {number} */ symbol) => readAccepts(layout, state, symbol),
    stepAscii: (/** @type {number} */ state, /** @type {string} */ text) => {
      let cur = state;
      for (let i = 0; i < text.length && cur >= 0; i++) cur = nextState(cur, asciiClass(text.codePointAt(i) ?? 0));
      return cur;
    },
  };
}

/**
 * @typedef {{
 *   word: (i: number) => number,
 *   readU32: (i: number) => number,
 *   wideBase: boolean,
 *   combLen: number,
 *   stateMetaOff: number,
 *   combOff: number,
 *   extTransOff: number,
 *   extAcceptsOff: number,
 * }} LexTableLayout
 */

/**
 * @param {LexTableLayout} layout
 * @param {number} state
 */
function readStateMeta(layout, state) {
  const o = layout.stateMetaOff + state * (layout.wideBase ? 5 : 4);
  return layout.wideBase
    ? { base: layout.readU32(o), tmpl: layout.word(o + 2), def: layout.word(o + 3), acc: layout.word(o + 4) }
    : { base: layout.word(o), tmpl: layout.word(o + 1), def: layout.word(o + 2), acc: layout.word(o + 3) };
}

/**
 * @param {LexTableLayout} layout
 * @param {number} state
 * @param {number} cls
 */
function readNextState(layout, state, cls) {
  const sm = readStateMeta(layout, state);
  const idx = sm.base + cls;
  const inComb = idx < layout.combLen && layout.word(layout.combOff + idx * 2) === sm.tmpl;
  const act = inComb ? layout.word(layout.combOff + idx * 2 + 1) : sm.def;
  if (act === 0) return -1;
  if ((act & 0x80_00) === 0) return act & 0x40_00 ? -1 : (act & 0x1f_ff) - 1;
  const p = layout.extTransOff + (act & 0x7f_ff);
  return layout.word(p + 1) & 1 ? -1 : layout.word(p);
}

/**
 * @param {LexTableLayout} layout
 * @param {number} state
 * @param {number} symbol
 */
function readAccepts(layout, state, symbol) {
  const acc = readStateMeta(layout, state).acc;
  if (acc === 0) return false;
  if ((acc & 0x80_00) === 0) return (acc & 0x3f_ff) - 1 === symbol;
  let p = layout.extAcceptsOff + (acc & 0x7f_ff);
  const flags = layout.word(p++);
  const fallbackSym = flags & 1 ? layout.word(p) : -1;
  if (flags & 1) p += 4;
  if (flags & 2) return fallbackSym === symbol;
  return Boolean(flags & 4) && layout.word(p) === symbol;
}

/**
 * @param {unknown} value
 * @param {Set<string>} output
 */
function collectTypeKeywords(value, output) {
  if (!value || typeof value !== 'object') return;
  if ('type' in value && value.type === 'SYMBOL' && 'name' in value && typeof value.name === 'string') {
    collectKeywords(grammar.rules[value.name], output);
    return;
  }
  for (const child of Object.values(value)) collectTypeKeywords(child, output);
}

/**
 * @param {unknown} value
 * @param {Set<string>} output
 * @param {boolean} lexical
 */
function collectKeywords(value, output, lexical = false) {
  if (!value || typeof value !== 'object') return;
  if (lexical && 'type' in value && value.type === 'SEQ') return;
  const token = lexical || ('type' in value && (value.type === 'TOKEN' || value.type === 'IMMEDIATE_TOKEN'));
  if (
    'type' in value &&
    value.type === 'STRING' &&
    'value' in value &&
    typeof value.value === 'string' &&
    /^[A-Za-z_][A-Za-z_0-9]*$/.test(value.value)
  ) {
    output.add(value.value);
  }
  for (const child of Object.values(value)) collectKeywords(child, output, token);
}
